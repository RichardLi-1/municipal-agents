const DICTS: Record<string, Record<string, string>> = { fr: FR };

export function hasDictionary(code: string) {
  return code === "en" || code in DICTS;
}

/** The language interface strings are shown in. */
export function chromeLang(code = lang.get()) {
  const base = code.split("-")[0];
  return hasDictionary(base) ? base : "en";
}

export function translate(text: string, vars?: Record<string, string | number>, code = chromeLang()): string {
  let s = DICTS[code]?.[text] ?? text;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Hook: re-renders when the language changes. */
export function useT() {
  const l = useStore(lang);
  const c = chromeLang(l);
  return (text: string, vars?: Record<string, string | number>) => translate(text, vars, c);
}

export function languageName(code: string, inLang?: string) {
  try {
    const n = new Intl.DisplayNames([inLang ?? code], { type: "language" }).of(code);
    return n ? n.charAt(0).toLocaleUpperCase(code) + n.slice(1) : code;
  } catch {
    return code;
  }
}
